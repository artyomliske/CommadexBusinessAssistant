"""Движение денег так, как его ведут в чатах.

В переписке лежит настоящий кассовый журнал: «оплата уличной двери 35к
взял с кассы -Покерная -займ», «795.000₽ приход с Пашковки», «8.000₽
выдал займ дом ростовка на материалы -трубы». Обычный «платёж» такое
описать не может: он теряет то, ради чего запись и делалась — откуда
деньги взяли и в каком качестве отдали.

Поэтому три независимых признака вместо одного:

* **направление** — пришло или ушло;
* **счёт** — наличные из кассы или безнал;
* **вид** — заём объекту, аванс работнику, оплата материала, приход от
  заказчика, возврат.

Направление и счёт дают остаток кассы. Вид и объект дают ответ на
вопрос «сколько вложено в Ростовку и сколько с неё вернулось». Вид и
человек — сколько за кем висит подотчёта.

Разделение не теоретическое. «Взял с кассы 35к и выдал займом на
Покерную» — это одновременно минус в кассе и плюс к вложенному в
объект; свести это одним полем нельзя.
"""

from __future__ import annotations

from enum import StrEnum


class Direction(StrEnum):
    IN = "in"
    """Приход: деньги пришли в компанию или вернулись в кассу."""
    OUT = "out"
    """Расход: деньги ушли."""


class Account(StrEnum):
    CASH = "cash"
    """Наличные в кассе."""
    BANK = "bank"
    """Безнал. В чатах пишут «б/н»."""
    UNKNOWN = "unknown"
    """Не сказано. Обычное дело: «17500 оплата на дом Ростовское шоссе».

    Отдельным значением, а не пустотой: «неизвестно откуда» и «из
    кассы» — разные утверждения, и в остаток кассы попадает только
    второе."""


class MovementKind(StrEnum):
    LOAN = "loan"
    """Заём объекту: деньги вложены в работы и вернутся с прихода."""
    ADVANCE = "advance"
    """Подотчёт: выдано человеку, ждём чеки."""
    MATERIAL = "material"
    """Оплата материалов."""
    LABOR = "labor"
    """Оплата работ: бригада, подрядчик, аванс плиточнику."""
    INCOME = "income"
    """Приход от заказчика по объекту."""
    RETURN = "return"
    """Возврат: сдали остаток в кассу, вернули заём."""
    OTHER = "other"


DIRECTIONS: dict[str, str] = {
    Direction.IN: "приход",
    Direction.OUT: "расход",
}

ACCOUNTS: dict[str, str] = {
    Account.CASH: "касса",
    Account.BANK: "б/н",
    Account.UNKNOWN: "не указано",
}

KINDS: dict[str, str] = {
    MovementKind.LOAN: "заём объекту",
    MovementKind.ADVANCE: "подотчёт",
    MovementKind.MATERIAL: "материалы",
    MovementKind.LABOR: "работы",
    MovementKind.INCOME: "приход от заказчика",
    MovementKind.RETURN: "возврат",
    MovementKind.OTHER: "прочее",
}


def signed(direction: str | None, amount: float | None) -> float:
    """Сумма со знаком: приход плюс, расход минус.

    Знак живёт здесь, а не в хранимых данных: в сообщении написано
    «взял 35к», и хранить это как −35000 значило бы записать не то, что
    сказал человек. Знак — вопрос прочтения, а не факта.
    """
    if amount is None:
        return 0.0
    return float(amount) if direction == Direction.IN else -float(amount)


def affects_cash(account: str | None) -> bool:
    """Влияет ли запись на остаток наличных.

    Только явная касса. Безнал и «не сказано» остаток не двигают:
    посчитать неизвестное как наличные — значит показать остаток,
    которого нет, и по нему кто-то поедет за деньгами.
    """
    return account == Account.CASH
