"""Постановка одобренного сообщения в очередь отправки.

Контролёр только принимает решение и записывает его. Наружу сообщение
уходит отдельной задачей воркера: у веб-процесса и у командной строки
нет клиента канала, и это намеренно — ходить наружу умеет один воркер.

Из этого следует неприятное: одобрить и не отправить — состояние
допустимое и внешне неотличимое от успеха. Так и вышло с командой
`digest --send`: она одобряла сводку, печатала «verdict: allow» и не
ставила задачу, а сообщение оставалось лежать в базе. Поэтому вызов
собран здесь: пять мест, которые обязаны сделать одно и то же, слишком
легко разъезжаются.
"""

from __future__ import annotations

from typing import Any

SEND_TASK = "send_outbound"


async def queue_send(redis: Any, outbound_id: int | None) -> bool:
    """Поставить отправку в очередь. False — отправлять нечего.

    Вызывать только после фиксации транзакции: иначе задача может
    начаться раньше, чем запись контролёра доедет до базы, и отправка
    не найдёт того, что должна отправить.
    """
    if outbound_id is None:
        return False
    await redis.enqueue_job(SEND_TASK, outbound_id)
    return True
