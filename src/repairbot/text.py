"""Русские числительные.

Отдельный модуль, потому что склонение нужно и в панели, и в сообщениях,
которые бот отправляет сам. Продублировать правило в двух местах значит
однажды получить «1 платежей» в одном и «5 платёж» в другом.

Форма выбирается по последней цифре с поправкой на второй десяток:
одиннадцать — не «один», а «одиннадцать платежей».
"""

from __future__ import annotations


def plural_form(number: int, one: str, few: str, many: str) -> str:
    """Форма слова для числа: 1 платёж, 2 платежа, 5 платежей."""
    number = abs(number)
    tail = number % 10
    teen = number % 100

    if 11 <= teen <= 14:
        # Второй десяток весь идёт по форме «много»: 11, 12, 13, 14 платежей.
        return many
    if tail == 1:
        return one
    if 2 <= tail <= 4:
        return few
    return many


def counted(number: int, one: str, few: str, many: str) -> str:
    """Число со словом в нужной форме: «5 платежей»."""
    return f"{number} {plural_form(number, one, few, many)}"


# Готовые формы для того, что встречается в панели чаще всего.
# Держим здесь, а не в шаблонах: одна опечатка в тройке форм заметна не
# сразу, и искать её потом по всем страницам не хочется.

WORDS: dict[str, tuple[str, str, str]] = {
    "чат": ("чат", "чата", "чатов"),
    "объект": ("объект", "объекта", "объектов"),
    "событие": ("событие", "события", "событий"),
    "сообщение": ("сообщение", "сообщения", "сообщений"),
    "вложение": ("вложение", "вложения", "вложений"),
    "документ": ("документ", "документа", "документов"),
    "файл": ("файл", "файла", "файлов"),
    "платёж": ("платёж", "платежа", "платежей"),
    "запись": ("запись", "записи", "записей"),
    "вопрос": ("вопрос", "вопроса", "вопросов"),
    "факт": ("факт", "факта", "фактов"),
    "черновик": ("черновик", "черновика", "черновиков"),
    "день": ("день", "дня", "дней"),
    "человек": ("человек", "человека", "человек"),
}


def count(number: int, word: str) -> str:
    """Число со словом по справочнику: `count(3, "чат")` → «3 чата».

    Незнакомое слово возвращается как есть — лучше «3 виджет», чем
    падение страницы из-за опечатки в шаблоне.
    """
    forms = WORDS.get(word)
    if forms is None:
        return f"{number} {word}"
    return counted(number, *forms)
